/**
 * Scan public/images/pictures/tours-vip/ and regenerate group-details-images.generated.ts
 *
 * Lets you add hero images manually for any group:
 * 1. Create folder: public/images/pictures/tours-vip/{groupCode}/
 * 2. Add images: group-details-1.jpg, group-details-2.png, etc.
 * 3. Run: pnpm scan:group-images (or node scripts/scan-group-details-folders.mjs)
 *
 * The API logic stays unchanged. This only populates the local manifest.
 */

import fs from 'fs'
import path from 'path'

const IMAGE_EXT = /\.(jpe?g|png|webp|gif)$/i

function main() {
  const baseDir = path.join(process.cwd(), 'public', 'images', 'pictures', 'tours-vip')
  if (!fs.existsSync(baseDir)) {
    fs.mkdirSync(baseDir, { recursive: true })
    console.log('Created:', baseDir)
    writeManifest({})
    return
  }

  const entries = fs.readdirSync(baseDir, { withFileTypes: true })
  const manifest = {}

  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const code = entry.name.trim()
    if (!code) continue

    const dir = path.join(baseDir, code)
    const files = listImages(dir).map((f) => ({ file: f, base: `/images/pictures/tours-vip/${code}` }))
    const subDirs = ['group-details', 'groups-details']
    for (const sub of subDirs) {
      const subDir = path.join(dir, sub)
      const subFiles = listImages(subDir).map((f) => ({
        file: f,
        base: `/images/pictures/tours-vip/${code}/${sub}`,
      }))
      files.push(...subFiles)
    }

    if (files.length === 0) continue

    const paths = files.map((f) => `${f.base}/${encodeURIComponent(f.file)}`)
    manifest[code] = paths
    console.log(`  ${code}: ${paths.length} image(s)`)
  }

  writeManifest(manifest)
  console.log(`\nDone. ${Object.keys(manifest).length} group(s) with hero images.`)
}

function listImages(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir)
    .filter((f) => IMAGE_EXT.test(f))
    .sort((a, b) => {
      const numA = parseInt(a.match(/(\d+)/)?.[1] ?? '0', 10)
      const numB = parseInt(b.match(/(\d+)/)?.[1] ?? '0', 10)
      if (numA !== numB) return numA - numB
      return a.localeCompare(b)
    })
}

function writeManifest(manifest) {
  const outPath = path.join(process.cwd(), 'src', 'data', 'group-details-images.generated.ts')
  const content = `/**
 * Auto-generated by scripts/scan-group-details-folders.mjs
 * Maps group code -> local image paths for group details hero galleries
 * Add images in public/images/pictures/tours-vip/{code}/ and run: pnpm scan:group-images
 */
export const GROUP_DETAILS_IMAGES: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)}
`
  fs.writeFileSync(outPath, content)
  console.log(`\nWrote: src/data/group-details-images.generated.ts`)
}

main()
